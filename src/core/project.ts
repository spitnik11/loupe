// Loupe project model — the non-destructive core.
// A recording is a PROJECT: original source video + input events + edit
// instructions. Nothing is ever baked into the source; edits are data.
// This is the whole reason one recording can export to 4 aspect ratios.

export const SCHEMA_VERSION = 1;

// --- Captured input, one row per event (persisted as events.jsonl) ---
export type EventType = "move" | "click" | "dblclick" | "scroll" | "key" | "nav";

export interface InputEvent {
  t: number; // seconds from recording start
  type: EventType;
  x?: number; // screen/canvas px (pointer events)
  y?: number;
  dy?: number; // scroll delta
  // Browser-tab capture can attach the clicked element's bounds — this is what
  // makes zoom target the button, not the cursor. Absent for native capture.
  el?: { x: number; y: number; w: number; h: number };
}

// --- Edit instructions (live in project.json, never touch the source) ---
export interface ZoomSegment {
  id: string;
  start: number; // seconds
  end: number;
  x: number; // focus target, normalized 0..1 of source frame
  y: number;
  scale: number; // 1 = no zoom; 2 = 2x
  auto: boolean; // generated by the zoom engine vs. hand-placed
}

export interface Cut {
  start: number;
  end: number;
} // removed span

export interface Background {
  type: "none" | "color" | "gradient" | "image";
  value?: string; // hex, css gradient, or asset path
}

export interface Frame {
  style: "none" | "minimal" | "mac" | "browser";
  radius: number;
  shadow: boolean;
  padding: number; // canvas padding around the capture, px at 1080p
}

export type Aspect = "16:9" | "9:16" | "1:1" | "4:5";

export interface Layout {
  scale: number;
  tracking?: "cursor" | "none"; // 9:16 usually tracks the cursor
}

export interface LoupeProject {
  schemaVersion: number;
  source: string; // relative path to source.webm
  duration: number; // seconds
  canvas: { aspect: Aspect };
  background: Background;
  frame: Frame;
  zooms: ZoomSegment[];
  cuts: Cut[];
  layouts: Partial<Record<Aspect, Layout>>;
}

export function newProject(source: string, duration: number): LoupeProject {
  return {
    schemaVersion: SCHEMA_VERSION,
    source,
    duration,
    canvas: { aspect: "16:9" },
    background: { type: "gradient", value: "linear-gradient(135deg,#1e293b,#0f172a)" },
    frame: { style: "minimal", radius: 18, shadow: true, padding: 48 },
    zooms: [],
    cuts: [],
    layouts: { "16:9": { scale: 0.92 } },
  };
}

// Effective playback time -> source time, accounting for cuts. Used by the
// player and renderer so a trimmed project maps back to real footage.
export function sourceTimeAt(editedT: number, cuts: Cut[]): number {
  let t = editedT;
  for (const c of [...cuts].sort((a, b) => a.start - b.start)) {
    if (t >= c.start) t += c.end - c.start;
  }
  return t;
}
