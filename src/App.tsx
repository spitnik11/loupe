import { useMemo } from "react";
import { newProject } from "./core/project.ts";
import { generateZooms } from "./core/zoom.ts";
import type { InputEvent } from "./core/project.ts";
import "./App.css";

// Phase 0 smoke screen: proves the framework-agnostic core is wired into the
// Tauri/React shell. Real editor UI is Phase 3.
const SAMPLE: InputEvent[] = [
  { t: 1.0, type: "click", x: 810, y: 430, el: { x: 720, y: 400, w: 180, h: 60 } },
  { t: 1.6, type: "click", x: 815, y: 435, el: { x: 720, y: 400, w: 180, h: 60 } },
  { t: 8.0, type: "click", x: 1500, y: 900 },
  { t: 8.4, type: "scroll", dy: 600, x: 1500, y: 900 },
];

function App() {
  const project = useMemo(() => newProject("source.webm", 12), []);
  const zooms = useMemo(() => generateZooms(SAMPLE, project.duration), [project]);

  return (
    <main className="container">
      <h1>Loupe</h1>
      <p className="tag">Record once → auto-zoomed camera work → export every aspect ratio.</p>

      <section>
        <h2>Phase 0 — core wired ✓</h2>
        <p>
          Sample of {SAMPLE.length} input events → <strong>{zooms.length}</strong> auto-zoom
          segment(s), generated by the engine (element-aware, clustered):
        </p>
        <ul>
          {zooms.map((z) => (
            <li key={z.id}>
              <code>{z.id}</code>: {z.start.toFixed(2)}s → {z.end.toFixed(2)}s @{z.scale}x,
              target ({z.x.toFixed(3)}, {z.y.toFixed(3)}){z.auto ? " · auto" : ""}
            </li>
          ))}
        </ul>
      </section>
    </main>
  );
}

export default App;
